/**
 * Optional captions for the "open file" view, keyed by file name (no extension).
 * Anything left out gets a title from its file name, e.g. "godzilla_minus_one"
 * -> "Godzilla Minus One".
 *
 * Example:
 *   rx7: { title: "RX-7 FD", label: "JDM // MAZDA", desc: "One line about it." },
 */
export const PICTURE_META: Record<string, { title?: string; label?: string; desc?: string }> = {};

const prettyName = (name: string) =>
  name.split(/[_-]+/).map((w) => w.charAt(0).toUpperCase() + w.slice(1)).join(" ");

export const TOTAL_CARDS = ARCHIVE_IMAGES.length;

/**
 * One card per photo (no duplicates), built from the list generated by
 * `python scripts/prepare_archive.py`.
 */
export const ARCHIVE_DATA: ArchiveItem[] = ARCHIVE_IMAGES.map((img, i) => {
  const meta = PICTURE_META[img.name] ?? {};
  const title = meta.title ?? prettyName(img.name);
  return {
    id: i,
    fileCode: `FILE // ${String(i + 1).padStart(3, "0")}`,
    url: img.url,
    title,
    label: meta.label ?? title.toUpperCase(),
    desc: meta.desc ?? "",
    status: "DECLASSIFIED",
    width: img.width,
    height: img.height,
    size: img.size,
  };
});

